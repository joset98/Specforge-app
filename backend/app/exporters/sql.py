from app.schemas import Column, PipelineResult, Table

TYPES = {
    "uuid": "UUID", "text": "TEXT", "integer": "INTEGER", "bigint": "BIGINT",
    "decimal": "NUMERIC(12,2)", "boolean": "BOOLEAN", "date": "DATE",
    "timestamp": "TIMESTAMPTZ", "json": "JSONB",
}


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _order(tables: list[Table]) -> list[Table]:
    """Topological order by FK dependency (Kahn); tables left in a cycle go last."""
    by_name = {t.name: t for t in tables}
    deps = {t.name: {c.foreign_key.partition(".")[0] for c in t.columns if c.foreign_key}
            & (by_name.keys() - {t.name}) for t in tables}
    ordered: list[str] = []
    ready = [t.name for t in tables if not deps[t.name]]
    while ready:
        name = ready.pop(0)
        ordered.append(name)
        for other in tables:
            pending = other.name not in ordered and other.name not in ready
            if pending and deps[other.name] <= set(ordered):
                ready.append(other.name)
    ordered += [t.name for t in tables if t.name not in ordered]
    return [by_name[n] for n in ordered]


def _fk(col: Column) -> tuple[str, str]:
    table, _, column = col.foreign_key.partition(".")
    return table, column


def to_sql(r: PipelineResult) -> str:
    tables = _order(r.architecture.tables)
    known = {t.name for t in tables}
    created: set[str] = set()
    out = ["-- Generated by AI Requirements Generator (PostgreSQL)", ""]
    deferred: list[str] = []
    for t in tables:
        lines = [f"  {_q(c.name)} {TYPES[c.type]}"
                 + (" NOT NULL" if c.primary_key or not c.nullable else "") for c in t.columns]
        pk = [_q(c.name) for c in t.columns if c.primary_key]
        if pk:
            lines.append(f"  PRIMARY KEY ({', '.join(pk)})")
        for c in t.columns:
            if not c.foreign_key:
                continue
            parent, pcol = _fk(c)
            ref = f"FOREIGN KEY ({_q(c.name)}) REFERENCES {_q(parent)} ({_q(pcol)})"
            if parent not in known:
                out.append(f"-- skipped {t.name}.{c.name}: unknown table {parent}")
            elif parent in created:
                lines.append(f"  {ref}")
            else:  # cycle or self-reference: add after every table exists
                deferred.append(f"ALTER TABLE {_q(t.name)} ADD CONSTRAINT "
                                f"{_q(f'fk_{t.name}_{c.name}')} {ref};")
        out += [f"CREATE TABLE {_q(t.name)} (", ",\n".join(lines), ");", ""]
        created.add(t.name)
    out += deferred
    return "\n".join(out).rstrip() + "\n"

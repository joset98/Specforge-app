from fastapi.testclient import TestClient

from app.exporters.sql import to_sql
from app.main import app
from app.schemas import Column, Table


def test_parent_created_before_child(sample_result):
    r = sample_result.model_copy(deep=True)
    r.architecture.tables.reverse()  # child listed first
    sql = to_sql(r)
    assert sql.startswith("-- Generated by AI Requirements Generator (PostgreSQL)")
    assert sql.index('CREATE TABLE "owners"') < sql.index('CREATE TABLE "pets"')
    assert 'FOREIGN KEY ("owner_id") REFERENCES "owners" ("id")' in sql
    assert "ALTER TABLE" not in sql


def test_types_and_not_null(sample_result):
    sql = to_sql(sample_result)
    assert '"id" UUID NOT NULL' in sql
    assert '"birth_date" DATE,' in sql or '"birth_date" DATE\n' in sql
    assert 'PRIMARY KEY ("id")' in sql


def test_cycle_uses_alter_table(sample_result):
    r = sample_result.model_copy(deep=True)
    r.architecture.tables = [
        Table(name="a", columns=[Column(name="id", type="uuid", primary_key=True),
                                 Column(name="b_id", type="uuid", foreign_key="b.id")]),
        Table(name="b", columns=[Column(name="id", type="uuid", primary_key=True),
                                 Column(name="a_id", type="uuid", foreign_key="a.id")]),
    ]
    sql = to_sql(r)
    assert 'CREATE TABLE "a"' in sql and 'CREATE TABLE "b"' in sql
    # a is created first, so b can reference it inline; only a -> b must wait.
    assert sql.count("ALTER TABLE") == 1
    assert 'FOREIGN KEY ("a_id") REFERENCES "a" ("id")' in sql
    assert 'ADD CONSTRAINT "fk_a_b_id" FOREIGN KEY ("b_id") REFERENCES "b" ("id");' in sql
    assert sql.index("ALTER TABLE") > sql.rindex("CREATE TABLE")


def test_self_reference_uses_alter_table(sample_result):
    r = sample_result.model_copy(deep=True)
    r.architecture.tables.append(Table(name="categories", columns=[
        Column(name="id", type="integer", primary_key=True),
        Column(name="parent_id", type="integer", foreign_key="categories.id")]))
    sql = to_sql(r)
    assert 'ADD CONSTRAINT "fk_categories_parent_id"' in sql


def test_composite_primary_key(sample_result):
    r = sample_result.model_copy(deep=True)
    r.architecture.tables.append(Table(name="tags", columns=[
        Column(name="pet_id", type="uuid", primary_key=True),
        Column(name="tag", type="text", primary_key=True)]))
    assert 'PRIMARY KEY ("pet_id", "tag")' in to_sql(r)


def test_export_sql_route_200(sample_result):
    res = TestClient(app).post("/api/export/sql", json=sample_result.model_dump())
    assert res.status_code == 200 and 'CREATE TABLE "owners"' in res.text
